def demo_events():
    names = {category["id"]: category["name"] for category in CATEGORIES}
    zone = ZoneInfo(DEMO_TIMEZONE)
    first_day = datetime.now(zone).date() + timedelta(days=1)
    result = []
    for city, (latitude, longitude) in CITIES.items():
        for index, template in enumerate(TEMPLATES):
            (
                title,
                category,
                price_min,
                price_max,
                description,
                place,
                artwork,
                tags,
                day,
                hour,
                minute,
                duration,
            ) = template
            start = datetime.combine(
                first_day + timedelta(days=day), time(hour, minute), zone
            ).astimezone(timezone.utc)
            result.append(
                {
                    "external_id": f"demo:{city}:{index}",
                    "title": title,
                    "description": description + DEMO_NOTICE,
                    "category": category,
                    "category_name": names[category],
                    "tags": list(tags),
                    "image_url": f"/art/{artwork}.svg",
                    "image_credit": "Иллюстрация приложения",
                    "start_date": start,
                    "end_date": start + timedelta(minutes=duration),
                    "timezone": DEMO_TIMEZONE,
                    "price_min": price_min,
                    "price_max": price_max,
                    "is_free": price_min == price_max == 0,
                    "city": city,
                    "location_name": place,
                    "address": "Демонстрационная локация в центре города",
                    "latitude": latitude + (index % 5 - 2) * 0.0015,
                    "longitude": longitude + ((index // 5) % 5 - 2) * 0.002,
                    "source_url": None,
                    "provider": "demo",
                }
            )
    return result
